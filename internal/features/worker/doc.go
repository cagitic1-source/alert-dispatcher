// Package worker читает алерты из Redis Stream alerts:pending через
// consumer group workers и доставляет их.
//
// Доставка at-least-once: сообщение подтверждается (XACK) только после
// завершения обработки. Если воркер упадёт посередине, сообщение останется
// в PEL и будет подобрано claimStale, поэтому каждый шаг обработки обязан
// быть идемпотентным. Отправка в DLQ защищена маркером, который ставится
// атомарно в Lua-скрипте вместе с записью в стрим.
//
// При неудачной доставке счётчик попыток увеличивается. Пока он меньше
// maxAttempts, повтор планируется в sorted set alerts:retry с
// экспоненциальной задержкой (baseRetryDelay * 2^(attempts-1)), а
// сообщение подтверждается. Периодический проход возвращает созревшие
// повторы в alerts:pending. Когда попытки исчерпаны, алерт один раз
