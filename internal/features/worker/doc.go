// Package worker
// 1. Читает сообщения из Redis Stream alerts:pending через consumer group workers.
// Для каждого: достаёт алерт из репозитория, пытается доставить,
// обновляет статус и подтверждает сообщение через XACK.
// 2. Гарантия доставки. At-least-once.
// Сообщение подтверждается только после обработки; если воркер умрёт посередине,
// сообщение останется в PEL и его подберёт claimStale.
// Следствие: одно и то же сообщение может быть обработано дважды,
// поэтому все операции обработчика должны быть идемпотентными — в том числе отправка в DLQ,
// которая защищена маркером через Lua-скрипт.
// 3. Неудачная доставка.
// Счётчик попыток растёт в репозитории.
// Пока он меньше maxAttempts,
// повтор планируется в sorted set alerts:retry с экспоненциально растущей задержкой.
// Когда попытки исчерпаны, алерт один раз отправляется в alerts:dead и получает статус failed.
